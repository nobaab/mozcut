/// Up to [n] real video files from the user's Documents folder.
List<String> sampleVideos([int n = 2]) {
  final dir = Directory('/Users/nobaab/Documents');
  if (!dir.existsSync()) return const [];
  final vids = dir
      .listSync()
      .whereType<File>()
      .map((f) => f.path)
      .where((p) => p.toLowerCase().endsWith('.mp4'))
      .toList()
    ..sort();
  return vids.take(n).toList();
}

/// Returns `(width, height)` of the first video stream in [path] via ffprobe.
Future<(int, int)> probeSize(String path) async {
  final r = await Process.run('ffprobe', [
    '-v', 'error',
    '-select_streams', 'v:0',
    '-show_entries', 'stream=width,height',
    '-of', 'csv=s=x:p=0',
    path,
  ]);
  final parts = r.stdout.toString().trim().split('x');
  return (int.parse(parts[0]), int.parse(parts[1]));
}

/// The capstone: drive the *exact* flow a creator uses to make a vertical
/// short — trim, an effect + a colour filter at partial intensity, a burned-in
/// title, an image (shape) sticker and a picture-in-picture video overlay —
/// through the real [Editor] + real [FfmpegEngine] + real video files, exported
/// to a real 1080x1920 (9:16) MP4, and prove the result is a genuine, playable,
/// correctly-sized vertical video with both audio and video streams. If this
/// passes, "edit a short and upload it tomorrow" works end to end.
void main() {
  final videos = sampleVideos(2);
  final skip =
      videos.length < 2 ? 'needs ≥2 .mp4 files in ~/Documents' : null;

  test('vertical 9:16 short with effect+filter+text+sticker+PiP exports a '
      'valid 1080x1920 MP4', () async {
    final container = ProviderContainer();
    addTearDown(container.dispose);
    final editor = container.read(editorProvider.notifier);
    final engine = container.read(engineProvider);

    final main = videos[0], pip = videos[1];

    // --- IMPORT + TRIM the main clip to a 3s hook (1..4s) ---
    await editor.addClip(main);
    final clipId = container.read(editorProvider).clips.single.id;
    editor.select(clipId);
    editor.trimSelected(inPoint: 1, outPoint: 4);
    expect(
        container.read(editorProvider).clips.single.duration, closeTo(3, 0.01));

    // --- EFFECT + COLOUR FILTER, each at partial intensity ---
    editor.setSelectedEffect('Gaussian Blur');
    editor.setSelectedEffectIntensity(0.5);
    editor.setSelectedFilter('Noir');
    editor.setSelectedFilterIntensity(0.6);
    final styled = container.read(editorProvider).clips.single;
    expect(styled.effectId, 'Gaussian Blur');
    expect(styled.effectIntensity, closeTo(0.5, 0.0001));
    expect(styled.filterId, 'Noir');
    expect(styled.filterIntensity, closeTo(0.6, 0.0001));

    // --- A SHAPE STICKER, generated by the engine like the Stickers panel ---
    final shapePath = await engine.generateShape('circle');
    expect(File(shapePath).existsSync(), isTrue);
    final sticker = StickerOverlay(
      imagePath: shapePath,
      start: 0,
      end: 3,
      size: 0.2,
      x: 0.8,
      y: 0.2,
    );

    // --- A BURNED-IN TITLE ---
    final title = TextOverlay(text: 'MozCut', start: 0, end: 3);

    // --- A PICTURE-IN-PICTURE VIDEO OVERLAY ---
    final overlay = VideoOverlay(
      sourcePath: pip,
      sourceDuration: await engine.probeDuration(pip),
      inPoint: 0,
      outPoint: 3,
      startTime: 0,
      scale: 0.4,
      posX: 0.3,
      posY: 0.75,
      opacity: 0.9,
    );

    // --- EXPORT at a vertical 9:16 shorts canvas ---
    final out =
        '${Directory.systemTemp.path}/mozcut_short_${DateTime.now().millisecondsSinceEpoch}.mp4';
    var progress = 0.0;
    await engine.export(
      clips: container.read(editorProvider).clips,
      outputPath: out,
      settings: const ExportSettings(),
      textOverlays: [title],
      stickerOverlays: [sticker],
      videoOverlays: [overlay],
      canvasWidth: 1080,
      canvasHeight: 1920,
      onProgress: (p) => progress = p,
    );
    expect(progress, 1.0);

    // --- VERIFY the deliverable ---
    final file = File(out);
    expect(file.existsSync(), isTrue);
    expect(file.lengthSync(), greaterThan(10000));
    expect(await engine.probeDuration(out), inInclusiveRange(2.5, 3.6));

    final (w, h) = await probeSize(out);
    expect(w, 1080, reason: 'exported at the vertical shorts width');
    expect(h, 1920, reason: 'exported at the vertical shorts height');

    final probe = await Process.run('ffprobe', [
      '-v', 'error',
      '-show_entries', 'stream=codec_type',
      '-of', 'default=noprint_wrappers=1:nokey=1',
      out,
    ]);
    final streams = probe.stdout.toString().trim().split('\n');
    expect(streams, containsAll(['video', 'audio']));

    file.deleteSync();
  }, timeout: const Timeout(Duration(minutes: 5)), skip: skip);
}
